function S = plot_style()
%PLOT_STYLE Unified palette and style constants.
%
% Also applies global font-size defaults (thesis with accessibility
% requirements: large text for low vision) on `groot`, so that ALL
% figures created after calling plot_style() inherit the sizes without
% each finish_figures having to specify them.
%
% Convention:
%   axis (ticks)      14 pt
%   labels (xlabel)   14·1.15 = 16.1 pt
%   title             14·1.25 = 17.5 pt
%   legend            13 pt
%   text() / texts    14 pt
%   colorbar          13 pt
%   sgtitle           18 pt  (does NOT inherit defaults; pass it as an argument
%                              in each call: sgtitle(.., 'FontSize',
%                              sty.fontSize.sg))

S.colors = struct( ...
    'fullyDigital',  [0.10 0.10 0.10], ...
    'fullyConn',     [0.18 0.44 0.71], ...
    'subConn',       [0.85 0.33 0.10], ...
    'theory',        [0.50 0.50 0.50], ...
    'accent1',       [0.47 0.67 0.19], ...
    'accent2',       [0.49 0.18 0.56], ...
    'accent3',       [0.93 0.69 0.13], ...
    'accent4',       [0.30 0.75 0.93]);

S.algColor = struct( ...
    'FD',          [0.10 0.10 0.10], ...
    'Chebyshev',   [0.18 0.44 0.71], ...
    'Taylor',      [0.47 0.67 0.19], ...
    'LS',          [0.85 0.33 0.10], ...
    'MVDR',        [0.49 0.18 0.56], ...
    'LCMV',        [0.93 0.69 0.13], ...
    'HybridFC',    [0.30 0.75 0.93], ...
    'HybridSC',    [0.80 0.20 0.50]);

S.algMarker = struct( ...
    'FD',         'o', ...
    'Chebyshev',  's', ...
    'Taylor',     'd', ...
    'LS',         '^', ...
    'MVDR',       'v', ...
    'LCMV',       'p', ...
    'HybridFC',   '>', ...
    'HybridSC',   '<');

% Okabe-Ito palette (colorblind-safe) for line series in academic
% figures. Unsaturated colors, also distinguishable in B/W by line/marker
% style. Added additively (does not alter S.colors/S.algColor).
S.okabeIto = struct( ...
    'black',         [0.00 0.00 0.00], ...
    'orange',        [0.902 0.624 0.000], ...
    'skyblue',       [0.337 0.706 0.914], ...
    'bluishgreen',   [0.000 0.620 0.451], ...
    'yellow',        [0.941 0.894 0.259], ...
    'blue',          [0.000 0.447 0.698], ...
    'vermillion',    [0.835 0.369 0.000], ...
    'reddishpurple', [0.800 0.475 0.655]);

S.fontSize.axis   = 14;
S.fontSize.label  = 16;     % label = axis * 1.15 rounded
S.fontSize.title  = 18;     % axes-level title (inside each subplot)
S.fontSize.sg     = 18;     % sgtitle (super-title above the subplots)
S.fontSize.legend = 13;
S.fontSize.text   = 14;     % text() annotations inside the figure
S.fontSize.cbar   = 13;     % colorbar

S.lineWidth      = 1.8;
S.markerSize     = 8;
S.figDpi         = 300;
S.figSize.single = [60 60 760 500];
S.figSize.dual   = [60 60 1080 500];
S.figSize.triple = [60 60 1360 500];
S.figSize.grid2  = [60 60 1140 800];
S.figSize.grid3  = [60 60 1360 940];

% --- Register global defaults (effect: ALL subsequent figures
%     inherit these sizes without setting them in each call) ---
set(groot, 'DefaultAxesFontSize',                 S.fontSize.axis);
set(groot, 'DefaultAxesTitleFontSizeMultiplier',  S.fontSize.title  / S.fontSize.axis);
set(groot, 'DefaultAxesLabelFontSizeMultiplier',  S.fontSize.label  / S.fontSize.axis);
set(groot, 'DefaultAxesTitleFontWeight',          'normal');   % non-bold titles (all figures)
set(groot, 'DefaultLegendFontSize',               S.fontSize.legend);
set(groot, 'DefaultTextFontSize',                 S.fontSize.text);
set(groot, 'DefaultColorbarFontSize',             S.fontSize.cbar);
set(groot, 'DefaultAxesLineWidth',                1.0);
end
